"""Produce an exact source/test/resource inventory for continuation and rollback."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
rows = []
for top in ('app', 'core', 'focus', 'training', 'college', 'feature', 'integration'):
    parent = root / top
    if not parent.exists():
        continue
    for file in sorted(parent.rglob('*')):
        if file.is_file() and not any(p in ('build', '.gradle') for p in file.relative_to(parent).parts):
            relative = file.relative_to(root).as_posix()
            kind = 'Test' if '/androidTest/' in relative or '/test/' in relative else 'Source/config/schema'
            rows.append(f'| `{relative}` | {kind} |')
target = root / 'docs/code_inventory.md'
target.write_text('# Exact implementation inventory\n\nGenerated by `python scripts/code_inventory.py`.\n'
                  'Ownership follows module paths; public contracts are in API/core modules.\n'
                  'Purpose comments in source and the progress log describe responsibilities.\n\n'
                  '| Path | Responsibility |\n|---|---|\n' + '\n'.join(rows) + '\n', encoding='utf-8')
print(f'Indexed {len(rows)} implementation files')
